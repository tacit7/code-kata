/** Resolve a LeetCode problem number to its canonical titleSlug, or null. */
export function leetcodeSlugFor(n: number): string | null {
  return LEETCODE_SLUGS[n] ?? null;
}

/** Resolve a seed kata to its LeetCode problem URL, or null if it is not a
 * LeetCode problem (or has no known slug). */
export function leetcodeUrlFor(kata: Pick<SeedKata, "name" | "language">): string | null {
  const n = leetcodeNumberFor(kata);
  if (n == null) return null;
  const slug = leetcodeSlugFor(n);
  return slug ? `https://leetcode.com/problems/${slug}/` : null;
}
